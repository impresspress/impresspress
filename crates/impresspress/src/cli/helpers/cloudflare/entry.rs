//! The main Worker's JavaScript entry module.
//!
//! Every main-Worker config [`super::wrangler`] generates names this module as
//! its `main`, and generating the config writes it beside the config. The
//! prepared runtime's module ([`super::prepared`]) re-exports it in turn, so
//! the dynamic candidate and the final version enter through the same code.
//!
//! The module is worker-build's shim with one change: its default export is
//! subclassed so that a Worker whose `IMPRESSPRESS_EXECUTOR_TRACE` var is
//! `"1"` logs an `ip-entry` line for each request before the shim's `fetch`
//! runs, that is before any Rust runs. `impresspress_cloudflare`'s
//! `executor_trace` module documents the signals and the shared state, whose
//! global and field names this module must keep in step with.
//!
//! The subclass composes with the shim rather than copying it. worker-build's
//! default export is a `Proxy` over its entrypoint class whose `construct`
//! trap returns a proxied instance, and that instance's `get` trap wraps every
//! method it returns in the shim's re-initialization check and
//! `WebAssembly.RuntimeError` catch. `new` on the subclass reaches that trap
//! with the subclass as `newTarget`, so the subclass's `fetch` is returned
//! through the same wrapper the shim's own `fetch` was, and `super.fetch`
//! is the shim's. Unset, the override delegates without reading or writing
//! anything but the var.

use std::path::{Path, PathBuf};

use anyhow::{Context, Result};

/// The entry module's file name, written into the config's own directory.
pub const ENTRY_MODULE_FILE: &str = "entry.mjs";

/// worker-build's shim, relative to the directory the main-Worker configs are
/// written to (`<repo>/target/impresspress-cloudflare`).
const WORKER_BUILD_SHIM: &str = "../../build/worker/shim.mjs";

/// The module's source. Deterministic: the same bytes on every deploy.
pub fn entry_module_source() -> String {
    format!(
        r#"// Generated by ImpressPress. Do not edit.
import Shim from '{WORKER_BUILD_SHIM}';
export * from '{WORKER_BUILD_SHIM}';

export default class extends Shim {{
  fetch(request) {{
    if (this.env.IMPRESSPRESS_EXECUTOR_TRACE === '1') {{
      const trace = (globalThis.__impresspressExecutorTrace ??= {{}});
      trace.isolateId ??= crypto.randomUUID().replaceAll('-', '');
      trace.wasmGeneration ??= 0;
      trace.seq = (trace.seq ?? 0) + 1;
      (trace.requests ??= new WeakMap()).set(request, trace.seq);
      console.log(`ip-entry ${{trace.isolateId}} ${{trace.wasmGeneration}} ${{trace.seq}}`);
    }}
    return super.fetch(request);
  }}
}}
"#
    )
}

/// Write the entry module into `out_dir`, the directory the config naming it
/// is written to, and return its path.
pub fn stage_entry_module(out_dir: &Path) -> Result<PathBuf> {
    let path = out_dir.join(ENTRY_MODULE_FILE);
    std::fs::write(&path, entry_module_source())
        .with_context(|| format!("write {}", path.display()))?;
    Ok(path)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn the_entry_module_subclasses_the_shim_default_and_reexports_the_rest() {
        let source = entry_module_source();
        assert!(source.contains("import Shim from '../../build/worker/shim.mjs';"));
        assert!(source.contains("export * from '../../build/worker/shim.mjs';"));
        assert!(source.contains("export default class extends Shim {"));
        assert!(
            source.contains("return super.fetch(request);"),
            "the shim's fetch must stay the one that runs:\n{source}"
        );
        assert!(
            !source.contains("export { default }"),
            "the shim's default is replaced by the subclass, not re-exported \
             beside it:\n{source}"
        );
    }

    /// Off unless exactly `"1"`, the spelling `CfEnvironment::
    /// executor_trace_enabled` tests for; and every trace statement sits
    /// inside that branch, so an untraced request runs nothing but the
    /// delegation.
    #[test]
    fn every_trace_statement_is_behind_the_var() {
        let source = entry_module_source();
        let gate = "if (this.env.IMPRESSPRESS_EXECUTOR_TRACE === '1') {";
        let (before, after) = source
            .split_once(gate)
            .unwrap_or_else(|| panic!("no gate in:\n{source}"));
        let (branch, rest) = after.split_once("\n    }\n").unwrap();
        for statement in [
            "globalThis.__impresspressExecutorTrace",
            "crypto.randomUUID()",
            "console.log(",
            ".set(request, trace.seq)",
        ] {
            assert!(branch.contains(statement), "{statement} not in the branch");
            assert!(!before.contains(statement), "{statement} before the gate");
            assert!(!rest.contains(statement), "{statement} after the gate");
        }
        assert!(branch.contains(
            "console.log(`ip-entry ${trace.isolateId} ${trace.wasmGeneration} ${trace.seq}`);"
        ));
    }

    /// The names the Rust side (`impresspress_cloudflare::executor_trace`)
    /// reads. A rename on either side breaks the join between `ip-entry` and
    /// `ip-poll`, so both are spelled out here.
    #[test]
    fn the_shared_state_uses_the_names_the_rust_side_reads() {
        let source = entry_module_source();
        for name in [
            "globalThis.__impresspressExecutorTrace",
            "trace.isolateId",
            "trace.wasmGeneration",
            "trace.requests",
        ] {
            assert!(source.contains(name), "{name} missing:\n{source}");
        }
    }

    #[test]
    fn staging_writes_the_same_bytes_every_time() {
        let out = tempfile::tempdir().unwrap();
        let first = stage_entry_module(out.path()).unwrap();
        let first_bytes = std::fs::read(&first).unwrap();
        let second = stage_entry_module(out.path()).unwrap();

        assert_eq!(first, out.path().join(ENTRY_MODULE_FILE));
        assert_eq!(second, first);
        assert_eq!(std::fs::read(&second).unwrap(), first_bytes);
        assert_eq!(first_bytes, entry_module_source().into_bytes());
    }
}
