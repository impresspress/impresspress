/**
 * The pages `visual-baseline.spec.ts` captures, desktop, shared with the
 * specs that check every captured page another way (`a11y.spec.ts`) and with
 * the read-only run's guard (`no-refusals.ts`).
 */
export interface Route {
  path: string;
  /** The baseline's name. */
  name: string;
  /** The status the server answers when the capture is of a refusal: the
   * seller pages, which this server answers 403 because seller products are
   * off. Every other route answers 200 (or, anonymous, a redirect or a 404
   * that is not a page). */
  refused?: 403;
  /** The server answers this path with a JSON error, not a page: a path
   * outside every block (`status-404`, which captures how a browser shows
   * it). Not an HTML document, so it has no landmarks or headings. */
  notAPage?: true;
}

